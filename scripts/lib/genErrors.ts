/**
 * The permission-error generator (DESIGN §2.2): one `Missing<Flag>` tagged error class per Discord permission
 * flag, the `PermissionErrors` lookup, the `missing` constructor table, the `MissingClasses` record and the
 * `ErrorCategories` runtime mirror (which also lists the D5 variants). Pure; `scripts/gen-errors.ts` reads
 * discord-api-types and does the I/O.
 *
 * The output has no `any` and no casts.
 */

/** Deprecated flag names that alias another flag's bit (H-059: `ManageEmojisAndStickers` is `ManageGuildExpressions`). */
export const deprecatedAliases: ReadonlySet<string> = new Set(["ManageEmojisAndStickers"])

/** Flags whose absence means the action cannot happen in this channel at all (category `access`). */
export const accessFlags: ReadonlyArray<string> = ["ViewChannel", "SendMessages", "SendMessagesInThreads", "Connect"]

/** Flags whose absence is fixable by removing part of the payload (category `payload`). */
export const payloadFlags: ReadonlyArray<string> = [
  "EmbedLinks",
  "AttachFiles",
  "SendTTSMessages",
  "SendPolls",
  "UseExternalEmojis",
  "UseExternalStickers",
  "MentionEveryone",
  "SendVoiceMessages"
]

/**
 * The same-tag variants (D5): for some operations, a generated class's tag with one more category. They are
 * written in `src/errors/Variants.ts`; the generator lists them here so `ErrorCategories` covers every class that
 * `errorFor` can build.
 */
export const variants: ReadonlyArray<{ readonly name: string; readonly flag: string; readonly adds: string }> = [
  { name: "MissingReadMessageHistoryForReply", flag: "ReadMessageHistory", adds: "payload" },
  { name: "MissingReadMessageHistoryForReaction", flag: "ReadMessageHistory", adds: "access" }
]

/** The relative path of the generated module. */
export const generatedPath = "src/errors/Missing.generated.ts"

/**
 * The flag names to generate: every key of discord-api-types' `PermissionFlagsBits` except the deprecated
 * aliases, sorted.
 *
 * @throws a defect when the input has an alias that is not listed (two kept names share a bit), a listed alias
 *   that does not alias a kept flag, or when a flag named in the category or variant tables does not exist.
 *   Each would make the generated classes silently wrong.
 */
export const permissionFlagNames = (bits: Readonly<Record<string, bigint>>): ReadonlyArray<string> => {
  const kept = Object.keys(bits)
    .filter((name) => !deprecatedAliases.has(name))
    .sort()
  const byBit = new Map<bigint, string>()
  for (const name of kept) {
    const bit = bits[name]
    if (bit === undefined) throw new Error(`flag ${name} has no bit`)
    const other = byBit.get(bit)
    if (other !== undefined) throw new Error(`flags ${other} and ${name} share bit ${bit}; list the deprecated one in deprecatedAliases`)
    byBit.set(bit, name)
  }
  for (const alias of deprecatedAliases) {
    const bit = bits[alias]
    if (bit !== undefined && !byBit.has(bit)) throw new Error(`deprecated alias ${alias} does not alias any kept flag`)
  }
  const known = new Set(kept)
  for (const flag of [...accessFlags, ...payloadFlags, ...variants.map((variant) => variant.flag)]) {
    if (!known.has(flag)) throw new Error(`the category or variant table names ${flag}, which is not a permission flag`)
  }
  return kept
}

/** A flag's categories in the order passed to `CategorizedError`: always `permission`, then `access`, then `payload`. */
export const categoriesOf = (flag: string): ReadonlyArray<string> => [
  "permission",
  ...(accessFlags.includes(flag) ? ["access"] : []),
  ...(payloadFlags.includes(flag) ? ["payload"] : [])
]

/** Every class name the mirror covers, with its sorted categories: the generated classes and the D5 variants. */
export const errorCategories = (flags: ReadonlyArray<string>): ReadonlyArray<readonly [string, ReadonlyArray<string>]> => {
  const entries: Array<readonly [string, ReadonlyArray<string>]> = flags.map((flag) => [`Missing${flag}`, [...categoriesOf(flag)].sort()])
  for (const variant of variants) entries.push([variant.name, [...new Set([...categoriesOf(variant.flag), variant.adds])].sort()])
  return entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
}

const quote = (text: string): string => JSON.stringify(text)

/** The full text of `src/errors/Missing.generated.ts` for the given flag names. */
export const renderMissingModule = (flags: ReadonlyArray<string>): string => {
  const lines: Array<string> = [
    "// GENERATED by scripts/gen-errors.ts from discord-api-types PermissionFlagsBits. Do not edit; run `bun run gen:errors`.",
    "/**",
    " * One tagged error class per Discord permission flag (DESIGN §2.2). Every class is in the `permission`",
    " * category; the access flags (ViewChannel, SendMessages, SendMessagesInThreads, Connect) are also `access`, and",
    " * the payload flags (EmbedLinks, AttachFiles, SendTTSMessages, SendPolls, UseExternalEmojis, UseExternalStickers,",
    " * MentionEveryone, SendVoiceMessages) are also `payload`.",
    " *",
    " * Library code never builds these through `missing` directly: it uses `errorFor(op, flag, cause)` from",
    " * `src/permissions/Operations.ts`, which builds the D5 variant an operation promises.",
    " */",
    'import { CategorizedError } from "./Category.ts"',
    'import { ErrorCause } from "./Cause.ts"',
    "",
    `/** Every Discord permission flag name, sorted. The deprecated alias ${[...deprecatedAliases].join(", ")} is dropped (H-059). */`,
    "export const PermissionFlags = [",
    ...flags.map((flag, index) => `  ${quote(flag)}${index < flags.length - 1 ? "," : ""}`),
    "] as const",
    "/** A Discord permission flag name. */",
    "export type PermissionFlag = (typeof PermissionFlags)[number]",
    ""
  ]
  for (const flag of flags) {
    const categories = categoriesOf(flag)
    lines.push(
      `/** The bot lacks the ${flag} permission for this operation. Categories: ${categories.join(", ")}. */`,
      `export class Missing${flag} extends CategorizedError<Missing${flag}>()(${quote(`Missing${flag}`)}, { cause: ErrorCause }, [`,
      `  ${categories.map(quote).join(", ")}`,
      "]) {",
      "  /** The missing flag. */",
      `  get flag(): ${quote(flag)} {`,
      `    return ${quote(flag)}`,
      "  }",
      "  override get message(): string {",
      `    return ${quote(`Missing permission ${flag} (`)} + this.cause.route + ")"`,
      "  }",
      "}",
      ""
    )
  }
  lines.push(
    "/** Flag name to class. Indexed by a union of flags it yields a plain union of classes, so hovers print class names. */",
    "export interface PermissionErrors {",
    ...flags.map((flag) => `  readonly ${flag}: Missing${flag}`),
    "}",
    "",
    "/** The constructor table: `missing[flag](cause)` with a generic flag `F` returns `PermissionErrors[F]`. */",
    "export const missing: { readonly [F in PermissionFlag]: (cause: ErrorCause) => PermissionErrors[F] } = {",
    ...flags.map((flag, index) => `  ${flag}: (cause) => new Missing${flag}({ cause })${index < flags.length - 1 ? "," : ""}`),
    "}",
    "",
    "/** Every generated class, keyed by class name. */",
    "export const MissingClasses = {",
    ...flags.map((flag, index) => `  Missing${flag}${index < flags.length - 1 ? "," : ""}`),
    "} as const",
    "",
    "/**",
    " * The runtime mirror of the category table: every generated class and every D5 variant",
    ` * (${variants.map((variant) => variant.name).join(", ")}), keyed by class name, with its sorted categories.`,
    " * Tests compare the markers the runtime builds with it (DESIGN §2.2, §4.7).",
    " */",
    "export const ErrorCategories = {"
  )
  const entries = errorCategories(flags)
  entries.forEach(([name, categories], index) => {
    lines.push(`  ${name}: [${categories.map(quote).join(", ")}]${index < entries.length - 1 ? "," : ""}`)
  })
  lines.push("} as const", "")
  return lines.join("\n")
}

/** The outcome of `gen:errors -- --check`. */
export type CheckResult = { readonly kind: "up-to-date" } | { readonly kind: "missing" } | { readonly kind: "stale"; readonly firstDifferentLine: number }

/** Compares the committed module (or its absence) with what the generator would write now. */
export const checkGenerated = (committed: string | undefined, rendered: string): CheckResult => {
  if (committed === undefined) return { kind: "missing" }
  if (committed === rendered) return { kind: "up-to-date" }
  const a = committed.split("\n")
  const b = rendered.split("\n")
  const index = a.findIndex((line, i) => line !== b[i])
  return { kind: "stale", firstDifferentLine: (index < 0 ? Math.min(a.length, b.length) : index) + 1 }
}
